function Nodes({ nodes }) {
  return (
    <div>
      {nodes.map((n, i) => (
        n.k === 'date' ? (
          <DateLine key={i}>{n.v}</DateLine>
        ) : n.k === 'h' ? (
          <H key={i}>{n.v}</H>
        ) : n.k === 'b' ? (
          <B key={i} items={n.items} />
        ) : (
          <P key={i}>{n.v}</P>
        )
      ))}
    </div>
  )
}

